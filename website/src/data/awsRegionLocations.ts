import type { MapPin } from "react-svg-worldmap";

export const AWS_REGIONS_SOURCE_URL =
  "https://docs.aws.amazon.com/global-infrastructure/latest/regions/aws-regions.html" as const;

export type AwsLocationPrecision =
  | "published-city"
  | "inferred-city"
  | "state-capital-fallback"
  | "country-capital-fallback";

export interface AwsRegionLocationPin extends MapPin {
  regionCode: string;
  awsName: string;
  city: string;
  adminArea?: string;
  country: string;
  precision: AwsLocationPrecision;
  locationPublished: boolean;
  sourceUrl: typeof AWS_REGIONS_SOURCE_URL;
}

const notPublished = " (location not published)";

function awsRegionPin({
  regionCode,
  awsName,
  city,
  adminArea,
  country,
  coordinates,
  precision,
  locationPublished,
}: Omit<
  AwsRegionLocationPin,
  "id" | "caption" | "sourceUrl"
>): AwsRegionLocationPin {
  const location = [city, adminArea, country].filter(Boolean).join(", ");
  return {
    id: `aws-${regionCode}`,
    regionCode,
    awsName,
    city,
    ...(adminArea != null ? { adminArea } : {}),
    country,
    coordinates,
    precision,
    locationPublished,
    sourceUrl: AWS_REGIONS_SOURCE_URL,
    kind: "aws-region",
    caption: `${regionCode}, ${awsName}, ${location}${
      locationPublished ? "" : notPublished
    }`,
  };
}

