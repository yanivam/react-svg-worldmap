import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const libRoot = path.resolve(__dirname, "..");

const assets = [
  {
    source: path.join(libRoot, "src/countries-reduced.topo.ts"),
    outputName: "countries-reduced.topo.cjs",
    metadataOutputName: "countries-reduced.metadata.ts",
  },
  {
    source: path.join(libRoot, "src/countries-detailed.topo.ts"),
    outputName: "countries-detailed.topo.cjs",
    metadataOutputName: "countries-detailed.metadata.ts",
  },
];

const outputDirs = [
  path.join(libRoot, "src/map-assets"),
  path.join(libRoot, "map-assets"),
];

function extractTopoData(sourceText, sourcePath) {
  const marker = "const topoData: any = ";
  const start = sourceText.indexOf(marker);
  const endMarker = ";\n\nexport default topoData;";
  const end = sourceText.indexOf(endMarker, start);

  if (start === -1 || end === -1) {
    throw new Error(
      `Could not find generated topoData export in ${path.relative(
        libRoot,
        sourcePath,
      )}`,
    );
  }

  return sourceText.slice(start + marker.length, end);
}

function extractTopologyMetadata(sourceText, sourcePath) {
  const marker = "export const topologyMetadata = ";
  const start = sourceText.indexOf(marker);
  const endMarker = " as const;\n\n// eslint-disable-next-line";
  const end = sourceText.indexOf(endMarker, start);

  if (start === -1 || end === -1) {
    throw new Error(
      `Could not find generated topologyMetadata export in ${path.relative(
        libRoot,
        sourcePath,
      )}`,
    );
  }

  return sourceText.slice(start + marker.length, end);
}

async function writeSharedAsset(outputDir, outputName, topoJson) {
  await mkdir(outputDir, { recursive: true });
  const outputPath = path.join(outputDir, outputName);
  await writeFile(
    outputPath,
    [
      "/* prettier-ignore */",
      "// AUTO-GENERATED by lib/scripts/build-shared-map-assets.mjs - do not edit manually.",
      `module.exports = ${topoJson};`,
      "",
    ].join("\n"),
    "utf8",
  );
}

async function writeMetadataAsset(outputName, metadataJson) {
  const outputDir = path.join(libRoot, "src/map-assets");
  await mkdir(outputDir, { recursive: true });
  await writeFile(
    path.join(outputDir, outputName),
    [
      "/* prettier-ignore */",
      "// AUTO-GENERATED by lib/scripts/build-shared-map-assets.mjs - do not edit manually.",
      `export const topologyMetadata = ${metadataJson} as const;`,
      "",
    ].join("\n"),
    "utf8",
  );
}

for (const asset of assets) {
  const sourceText = await readFile(asset.source, "utf8");
  const topoJson = extractTopoData(sourceText, asset.source);
  const metadataJson = extractTopologyMetadata(sourceText, asset.source);

  await Promise.all(
    outputDirs.map((outputDir) =>
      writeSharedAsset(outputDir, asset.outputName, topoJson),
    ),
  );
  await writeMetadataAsset(asset.metadataOutputName, metadataJson);
}

console.log(
  `[build-shared-map-assets] Wrote ${assets.length} shared topology assets to src/map-assets and map-assets.`,
);
